def build_md(info: dict) -> str:
    tables, pks, hyper = info["tables"], info["pks"], info["hyper"]
    now = datetime.now(timezone.utc).strftime("%Y-%m-%d")
    lines = [
        "# مخطط قاعدة opensky — مولَّد آلياً",
        "",
        f"آخر هجرة: **{info['version']}** · جداول: {len(tables)} · hypertables: "
        f"{len(hyper)} · وُلِّد {now} عبر `scripts/generate_erd.py` — لا يُحرَّر يدوياً.",
        "",
        "العلاقة المُعلنة الوحيدة FK: `notify_outbox → notify_subscribers` (هجرة 040) — "
        "البقية منطقية يفرضها التطبيق (TimescaleDB يمنع FK نحو hypertable).",
        "",
        "```mermaid",
        "erDiagram",
    ]
    for f in info["fks"]:
        lines.append(f'    {f["src"]} }}o--|| {f["dst"]} : FK')
    for s, d, via in LOGICAL_LINKS:
        lines.append(f'    {s} }}o..o{{ {d} : "{via}"')
    lines.append("```")
    by_domain: dict[str, list[str]] = {k: [] for k in DOMAINS}
    for t in sorted(tables):
        by_domain[META.get(t, ("misc", ""))[0]].append(t)
    for dkey, dname in DOMAINS.items():
        if not by_domain[dkey]:
            continue
        lines += ["", f"## {dname}", ""]
        for t in by_domain[dkey]:
            meta = tables[t]
            tags = " · hypertable" if t in hyper else ""
            lines.append(f"### `{t}`{tags} (≈{fmt_rows(meta.get('est_rows', -1))} صف)")
            lines.append(META.get(t, ("misc", ""))[1] or "")
            cols = ", ".join(
                f"`{c['column_name']}`" + ("🔑" if c["column_name"] in pks.get(t, set()) else "")
                for c in meta.get("cols", []))
            lines += [cols, ""]
    return "\n".join(lines) + "\n"


